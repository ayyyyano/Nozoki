// Snapshot the locked Varlet theme variables for SSR and no-JavaScript first paint.
import light from '@varlet/ui/es/themes/md3-light/index.mjs'
import dark from '@varlet/ui/es/themes/md3-dark/index.mjs'
import { writeFile } from 'node:fs/promises'
import { format, resolveConfig } from 'prettier'
import { fileURLToPath } from 'node:url'
import { createThemeColors } from '../shared/domain/theme-colors.ts'
Object.assign(light, createThemeColors('#6750A4', false))
Object.assign(dark, createThemeColors('#6750A4', true))
const declarations = (theme) =>
  Object.entries(theme)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n')
const css = `/*! Varlet 3.20.7 theme variables. Copyright (c) 2024 varletjs, MIT; /licenses/varlet.txt. Generated by scripts/generate-m3-themes.mjs. */
:root:root {\n  color-scheme: light;\n${declarations(light)}\n}
@media (prefers-color-scheme: dark) {
  :root:not([data-nozoki-mode='light']) {\n    color-scheme: dark;\n${declarations(dark)}\n  }
}
:root[data-nozoki-mode='dark'] {\n  color-scheme: dark;\n${declarations(dark)}\n}
`
await writeFile(
  new URL('../app/assets/styles/m3-themes.css', import.meta.url),
  await format(css, {
    ...(await resolveConfig(fileURLToPath(new URL('../.prettierrc.json', import.meta.url)))),
    parser: 'css',
  }),
)
await import('./build-theme-init.mjs')
